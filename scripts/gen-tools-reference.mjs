#!/usr/bin/env node
/**
 * Regenerate the two tool references from Swiggy's own documentation dump, so they cannot drift
 * by hand:
 *
 *   skills/swiggy-mcp/references/tools.md   full reference (description + parameter table per tool)
 *   wiki/tools-catalog.md                   one-line-per-tool catalog
 *
 *   node scripts/gen-tools-reference.mjs                 # fetches https://mcp.swiggy.com/builders/llms-full.txt
 *   node scripts/gen-tools-reference.mjs ./llms-full.txt # or reads a local copy
 *   node scripts/gen-tools-reference.mjs --check         # exit 1 if the tool list differs from src/lib/aliases.ts
 *
 * After a run that changes the tool list, update TOOL_CATALOG in src/lib/aliases.ts to match
 * (`--check` tells you what differs) and the counts in README.md / AGENTS.md.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SOURCE = "https://mcp.swiggy.com/builders/llms-full.txt";
const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const args = process.argv.slice(2);
const check = args.includes("--check");
const local = args.find((a) => !a.startsWith("--"));

const SERVERS = [
  { key: "food", label: "Food", path: "food" },
  { key: "instamart", label: "Instamart", path: "im" },
  { key: "dineout", label: "Dineout", path: "dineout" },
  { key: "scenes", label: "Scenes", path: "scenes" },
];
/** Destructive in this CLI (confirmation / --yes). Mirrors DESTRUCTIVE_TOOLS in src/lib/aliases.ts. */
const DESTRUCTIVE = new Set(["place_food_order", "checkout", "book_table", "place_event_order", "flush_food_cart", "clear_cart", "delete_address"]);

const text = local ? readFileSync(local, "utf8") : await (await fetch(SOURCE, { headers: { "user-agent": "swiggy-cli-docs-gen" } })).text();
const today = new Date().toISOString().slice(0, 10);

const tools = { food: [], instamart: [], dineout: [], scenes: [] };
for (const page of text.replace(/\r\n/g, "\n").split("\n---\n\n### ")) {
  const head = /^([a-z_]+)\n\n<https:\/\/mcp\.swiggy\.com\/builders\/docs\/reference\/(food|instamart|dineout|scenes)\/[a-z_]+\.md>\n\n/.exec(page);
  if (!head) continue;
  const [, name, server] = head;
  const body = page.slice(head[0].length);
  // The page opens with a truncated one-liner, then the full description, then "## Example".
  const intro = body.split("\n## ")[0].trim().split("\n\n");
  const description = unescapeHtml((intro.length > 1 ? intro.slice(1).join("\n\n") : intro[0]).trim());
  const params = [];
  const table = /## Parameters\n\n([\s\S]*?)\n\n/.exec(body);
  if (table) {
    for (const line of table[1].split("\n").slice(2)) {
      const cells = splitRow(line);
      if (cells.length < 3) continue;
      params.push({ name: cells[0].replace(/`/g, ""), type: cells[1].replace(/`/g, ""), required: /yes/i.test(cells[2]), notes: unescapeHtml(cells.slice(3).join(" | ")) });
    }
  }
  const stage = /\| \*\*Stage\*\* \| ([^|]+) \|/.exec(body)?.[1].trim() ?? "";
  const behaviour = /\| \*\*Behaviour\*\* \| ([^|]+) \|/.exec(body)?.[1].trim() ?? "";
  tools[server].push({ name, description, params, stage, behaviour });
}
for (const list of Object.values(tools)) list.sort((a, b) => a.name.localeCompare(b.name));

const total = Object.values(tools).reduce((n, l) => n + l.length, 0);
if (total === 0) {
  console.error("No tool pages found. Did the format of llms-full.txt change?");
  process.exit(1);
}
const counts = SERVERS.map((s) => `${s.label} ${tools[s.key].length}`).join(", ");

if (check) {
  const src = readFileSync(join(root, "src/lib/aliases.ts"), "utf8");
  const block = /export const TOOL_CATALOG[\s\S]*?\n} as const;/.exec(src)?.[0] ?? "";
  let drift = false;
  for (const s of SERVERS) {
    const inSrc = new Set([...(new RegExp(`\\n  ${s.key}: \\[([\\s\\S]*?)\\n  \\],`).exec(block)?.[1] ?? "").matchAll(/"([a-z_]+)"/g)].map((m) => m[1]));
    const inDocs = new Set(tools[s.key].map((t) => t.name));
    const added = [...inDocs].filter((n) => !inSrc.has(n));
    const removed = [...inSrc].filter((n) => !inDocs.has(n));
    if (added.length || removed.length) {
      drift = true;
      console.log(`${s.key}: ${added.length ? `new upstream: ${added.join(", ")}` : ""}${added.length && removed.length ? "; " : ""}${removed.length ? `gone upstream: ${removed.join(", ")}` : ""}`);
    }
  }
  console.log(drift ? "TOOL_CATALOG differs from Swiggy's published reference." : `TOOL_CATALOG matches Swiggy's published reference (${total} tools: ${counts}).`);
  process.exit(drift ? 1 : 0);
}

/* ---------------- full reference ---------------- */
const full = [
  `# Swiggy tool reference (${total} tools)`,
  "",
  `Generated by \`scripts/gen-tools-reference.mjs\` from ${SOURCE} on ${today}. Do not edit by hand. Parameter names are exact (camelCase). Session credentials are never passed as arguments.`,
  "",
  "Read results from `structuredContent`; when it is missing or empty (possible on Dineout and Scenes) read the JSON envelope `{ success, data, message? }` in the first `content` block, plus any fields that sit next to `data`. A failed call sets `isError: true` or returns `{ success: false, error: { message } }`.",
  "",
  "Live source of truth: `https://mcp.swiggy.com/builders/docs/reference/<server>/<tool>.md`",
  "",
];
for (const s of SERVERS) {
  full.push(`## ${s.label} — \`POST https://mcp.swiggy.com/${s.path}\` (${tools[s.key].length} tools)`, "");
  for (const t of tools[s.key]) {
    full.push(`### \`${t.name}\`  ·  ${[t.stage, t.behaviour].filter(Boolean).join(" · ")}`, "", t.description, "");
    if (t.params.length) {
      full.push("| Param | Type | Required | Notes |", "| --- | --- | --- | --- |");
      for (const p of t.params) full.push(`| \`${p.name}\` | \`${p.type}\` | ${p.required ? "yes" : "no"} | ${p.notes} |`);
    } else {
      full.push("No parameters.");
    }
    full.push("");
  }
}
writeFileSync(join(root, "skills/swiggy-mcp/references/tools.md"), full.join("\n"));

/* ---------------- catalog ---------------- */
const cat = [
  "# Tools catalog",
  "",
  `Generated by \`scripts/gen-tools-reference.mjs\` from <https://mcp.swiggy.com/builders/docs/reference/> on **${today}** — **${total} tools** across ${SERVERS.length} servers (${counts}). Do not edit by hand. Parameter names are verbatim from the reference (camelCase). The full reference with descriptions is in [\`skills/swiggy-mcp/references/tools.md\`](../skills/swiggy-mcp/references/tools.md).`,
  "",
  "⚠ = destructive in this CLI (gated by confirmation / `--yes`). Stage and behaviour come from Swiggy's reference.",
  "",
];
for (const s of SERVERS) {
  cat.push(`## ${s.label} (\`https://mcp.swiggy.com/${s.path}\`) — ${tools[s.key].length} tools`, "", "| Tool | Stage | Behaviour | Required params | Optional params |", "| --- | --- | --- | --- | --- |");
  for (const t of tools[s.key]) {
    const req = t.params.filter((p) => p.required).map((p) => `\`${p.name}\``).join(", ") || "—";
    const opt = t.params.filter((p) => !p.required).map((p) => `\`${p.name}\``).join(", ") || "—";
    cat.push(`| \`${t.name}\`${DESTRUCTIVE.has(t.name) ? " ⚠" : ""} | ${t.stage} | ${t.behaviour} | ${req} | ${opt} |`);
  }
  cat.push("");
}
cat.push(
  "## Shared Payment stage",
  "",
  "`get_payment_options`, `check_payment_status` and `confirm_order` exist on every server with the same shape; the place-order tool differs (`place_food_order` / `checkout` / `book_table` / `place_event_order`). Scenes needs the `cartKey` from `create_event_cart` for `get_payment_options` and never offers Cash. See [payments.md](./payments.md).",
  "",
  "## Tools the CLI still has commands for, but Swiggy no longer publishes",
  "",
  "These were in the September 2026 reference and are absent from the November 2026 one. Swiggy enables tools per account, so a signed-in `swiggy doctor` is the only way to tell whether yours still has them. Their commands are marked `[legacy]` in `--help`.",
  "",
  "| Server | Tool | CLI command |",
  "| --- | --- | --- |",
  "| Instamart | `apply_coupon` | `swiggy instamart apply-coupon` |",
  "| Instamart | `list_coupons` | `swiggy instamart list-coupons` |",
  "| Instamart | `get_order_details` | `swiggy instamart order` |",
  "| Dineout | `cancel_booking` | `swiggy dineout cancel` |",
  "| Dineout | `get_saved_locations` | `swiggy dineout locations` (the tool now lives on Scenes: `swiggy scenes locations`) |",
  ""
);
writeFileSync(join(root, "wiki/tools-catalog.md"), cat.join("\n"));

console.log(`Wrote ${total} tools (${counts}).`);

function splitRow(line) {
  // Split a Markdown table row on unescaped pipes.
  return line
    .replace(/^\||\|$/g, "")
    .split(/(?<!\\)\|/)
    .map((c) => c.trim());
}
function unescapeHtml(s) {
  return s.replace(/&#123;/g, "{").replace(/&#125;/g, "}").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
}
